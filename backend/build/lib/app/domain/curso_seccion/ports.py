from dataclasses import dataclass
from typing import Protocol

from app.domain.curso_seccion.entities import Comunicado, CursoSeccion


@dataclass(frozen=True)
class AlumnoDeCurso:
    perfil_alumno_id: int
    nombre: str
    apellidos: str


class RepositorioCursosSeccion(Protocol):
    def crear(self, curso: CursoSeccion) -> CursoSeccion: ...
    def buscar_por_id(self, curso_id: int) -> CursoSeccion | None: ...
    def listar_por_profesor(self, profesor_id: int) -> list[CursoSeccion]: ...
    def agregar_alumno(self, curso_id: int, perfil_alumno_id: int) -> None: ...
    def quitar_alumno(self, perfil_alumno_id: int) -> None: ...
    def listar_alumnos(self, curso_id: int) -> list[AlumnoDeCurso]: ...
    def buscar_curso_del_alumno(self, perfil_alumno_id: int) -> CursoSeccion | None: ...


class RepositorioComunicados(Protocol):
    def crear(self, comunicado: Comunicado) -> Comunicado: ...
    def listar_por_curso(self, curso_id: int) -> list[Comunicado]: ...
